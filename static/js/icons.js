/** El SVG de un icono. `clase` permite otro tamaño: "ic-lg", "ic-sm". */
export function icon(nombre, clase = "") {
  const trazo = TRAZOS[nombre];
  if (!trazo) return "";
  return `<svg class="ic ${clase}" viewBox="0 0 24 24" fill="none" stroke="currentColor"
    stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round"
    aria-hidden="true" focusable="false">${trazo}</svg>`;
}

/** Atajo para interpolar: `${IC.plane}`. */
export const IC = new Proxy({}, { get: (_, nombre) => icon(String(nombre)) });

/** Rellena los `<span data-icon="…">` del HTML estático. */
export function pintarIconos(raiz = document) {
  raiz.querySelectorAll("[data-icon]").forEach((el) => {
    el.innerHTML = icon(el.dataset.icon, el.dataset.iconSize || "");
  });
}
